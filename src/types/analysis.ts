export type Ecosystem = 'npm' | 'PyPI' | 'maven' | 'nuget' | 'cargo' | 'go' | 'rubygems' | 'packagist' | 'pub' | 'hex' | 'cocoapods' | 'swiftpm' | 'conda' | 'linux' | 'oci';
export type RiskStatus = 'verified' | 'warning' | 'high_risk';
export type ChangeType = 'added' | 'removed' | 'modified' | 'unchanged';
export type RiskLevel = 'none' | 'low' | 'medium' | 'high';

export interface PackageRef {
  name: string;
  ecosystem: Ecosystem;
  version: string;
}

export interface AnalysisRequest {
  ecosystem: Ecosystem;
  name: string;
  version: string;
  repoUrl: string;
}

export interface DetectedPackage {
  ecosystem: Exclude<Ecosystem, 'PyPI'> | 'pypi';
  name: string;
  version: string;
  manifest: string;
}

export interface RepositoryDetection {
  repository: string;
  defaultBranch: string;
  truncated: boolean;
  packages: DetectedPackage[];
}

export interface FileChange {
  path: string;
  changeType: ChangeType;
  risk: RiskLevel;
  reason?: string;
  /** AI-generated elaboration of why this file's difference matters, grounded in a deterministic finding. */
  aiNote?: string;
  /** Unified-diff style text. */
  diff?: string;
}

export interface FindingDetail {
  /** Short evidence line, shown by default. */
  summary: string;
  risk: RiskLevel;
  /** Why this finding matters, shown only when the user expands it. */
  explanation?: string;
  /** What to do about it, shown only when the user expands it. */
  recommendation?: string;
}

export interface RiskAssessment {
  status: RiskStatus;
  /** 0 (no concern) to 100 (severe). */
  score: number;
  findings: FindingDetail[];
}

export interface Provenance {
  sourceRepo: string;
  sourceCommit?: string;
  publishedAt: string;
  publisher: string;
  registryChecksum: string;
  signatureVerified: boolean;
  buildProvenance: boolean;
  attestation: string;
}

export interface ComparisonSummary {
  added: number;
  removed: number;
  modified: number;
  unchanged: number;
}

/** Row shown in the dashboard and history tables. */
export interface AnalysisSummary {
  id: string;
  package: PackageRef;
  sourceRepo: string;
  status: RiskStatus;
  createdAt: string;
}

export interface AnalysisResult extends AnalysisSummary {
  risk: RiskAssessment;
  /** Generated by the backend (GPT-OSS-120B). Kept separate from structured findings. */
  aiExplanation: string;
  comparison: ComparisonSummary;
  files: FileChange[];
  provenance: Provenance;
  /** True when this result was served from the shared cache instead of a fresh analysis. */
  fromCache?: boolean;
}

/** Progress reported by the backend while it boots up. */
export interface StartupProgress {
  phase: string;
  percent: number;
  message: string;
  ready: boolean;
  startedAt?: number;
}

/** Progress reported by the backend while a single analysis runs. */
export interface AnalysisProgress {
  id: string;
  status: "queued" | "running" | "done" | "failed";
  percent: number;
  stage: string;
  message: string;
  createdAt: number;
  finishedAt?: number | null;
  error?: string | null;
  errorCode?: string | null;
}
